// registerTenant creates a business, its first admin and a starter template in one transaction.
func (a *App) registerTenant(business, email, hash, starterZPL string) error {
	tx, err := a.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var tid int64
	if err := tx.QueryRow(rebind(`INSERT INTO tenants(name) VALUES(?) RETURNING id`), business).Scan(&tid); err != nil {
		return err
	}
	if _, err := tx.Exec(rebind(`INSERT INTO users(tenant_id,email,pass_hash,role) VALUES(?,?,?,'admin')`), tid, email, hash); err != nil {
		return uniqueErr(err)
	}
	if _, err := tx.Exec(rebind(`INSERT INTO templates(tenant_id,name,zpl) VALUES(?,?,?)`), tid, "Starter label (text only)", starterZPL); err != nil {
		return err
	}
	return tx.Commit()
}

func (a *App) userByEmail(email string) (*User, error) {
	u := &User{}
	err := a.queryRow(`SELECT id,tenant_id,email,role,pass_hash FROM users WHERE email=?`, email).Scan(&u.ID, &u.TenantID, &u.Email, &u.Role, &u.hash)
	return u, err
}
func (a *App) userBySession(token string) (*User, error) {
	u := &User{}
	err := a.queryRow(`SELECT u.id,u.tenant_id,t.name,u.email,u.role,u.pass_hash FROM sessions s
		JOIN users u ON u.id=s.user_id JOIN tenants t ON t.id=u.tenant_id
		WHERE s.token=? AND s.expires_at>?`, token, time.Now().Unix()).Scan(&u.ID, &u.TenantID, &u.TenantName, &u.Email, &u.Role, &u.hash)
	return u, err
}
func (a *App) createSession(token string, uid int64, ttl time.Duration) error {
	a.exec(`DELETE FROM sessions WHERE expires_at<?`, time.Now().Unix()) // opportunistic cleanup
	_, err := a.exec(`INSERT INTO sessions(token,user_id,expires_at) VALUES(?,?,?)`, token, uid, time.Now().Add(ttl).Unix())
	return err
}
func (a *App) deleteSession(token string) { a.exec(`DELETE FROM sessions WHERE token=?`, token) }

func (a *App) setPassword(uid int64, hash, keepToken string) error {
	if _, err := a.exec(`UPDATE users SET pass_hash=? WHERE id=?`, hash, uid); err != nil {
		return err
	}
	_, err := a.exec(`DELETE FROM sessions WHERE user_id=? AND token<>?`, uid, keepToken)
	return err
}

func (a *App) listTeam(tenant int64) ([]User, error) {
	rows, err := a.query(`SELECT id,email,role FROM users WHERE tenant_id=? ORDER BY role, email`, tenant)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []User
	for rows.Next() {
		var u User
		if err := rows.Scan(&u.ID, &u.Email, &u.Role); err != nil {
			return nil, err
		}
		out = append(out, u)
	}
	return out, rows.Err()
}

// Admins manage non-admin accounts only (role='user') inside their own business.
func (a *App) getTeamUser(tenant, id int64) (User, error) {
	var u User
	err := a.queryRow(`SELECT id,email,role FROM users WHERE id=? AND tenant_id=? AND role='user'`, id, tenant).Scan(&u.ID, &u.Email, &u.Role)
	return u, err
}
func (a *App) createTeamUser(tenant int64, email, hash string) error {
	_, err := a.exec(`INSERT INTO users(tenant_id,email,pass_hash,role) VALUES(?,?,?,'user')`, tenant, email, hash)
	return uniqueErr(err)
}
func (a *App) updateTeamUser(tenant, id int64, email, hash string) error {
	var res sql.Result
	var err error
	if hash == "" {
		res, err = a.exec(`UPDATE users SET email=? WHERE id=? AND tenant_id=? AND role='user'`, email, id, tenant)
	} else {
		res, err = a.exec(`UPDATE users SET email=?,pass_hash=? WHERE id=? AND tenant_id=? AND role='user'`, email, hash, id, tenant)
	}
	if err != nil {
		return uniqueErr(err)
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return sql.ErrNoRows
	}
	if hash != "" {
		_, err = a.exec(`DELETE FROM sessions WHERE user_id=?`, id) // password reset signs them out
	}
	return err
}
func (a *App) deleteTeamUser(tenant, id int64) error {
	_, err := a.exec(`DELETE FROM users WHERE id=? AND tenant_id=? AND role='user'`, id, tenant)
	return err
}

