func (a *App) saveTemplate(tenant int64, t Template) error {
	var err error
	if t.ID == 0 {
		_, err = a.exec(`INSERT INTO templates(tenant_id,name,zpl) VALUES(?,?,?)`, tenant, t.Name, t.ZPL)
		return err
	}
	res, err := a.exec(`UPDATE templates SET name=?,zpl=?,updated_at=now() WHERE id=? AND tenant_id=?`, t.Name, t.ZPL, t.ID, tenant)
	if err == nil {
		if n, _ := res.RowsAffected(); n == 0 {
			err = sql.ErrNoRows
		}
	}
	return err
}
