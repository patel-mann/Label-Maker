// Every business-owned table carries tenant_id, and every query below filters on it.
// Each statement is listed separately because the driver runs one command per Exec.
var schema = []string{
	`CREATE TABLE IF NOT EXISTS tenants (
	  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	  name TEXT NOT NULL,
	  created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE TABLE IF NOT EXISTS users (
	  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	  tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
	  email TEXT NOT NULL,
	  pass_hash TEXT NOT NULL,
	  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin','user')),
	  created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users(lower(email))`,
	`CREATE TABLE IF NOT EXISTS sessions (
	  token TEXT PRIMARY KEY,
	  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	  expires_at BIGINT NOT NULL)`,
	`CREATE TABLE IF NOT EXISTS templates (
	  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	  tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
	  name TEXT NOT NULL,
	  zpl TEXT NOT NULL,
	  updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE TABLE IF NOT EXISTS products (
	  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	  tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
	  name TEXT NOT NULL,
	  template_id BIGINT REFERENCES templates(id) ON DELETE SET NULL,
	  barcode TEXT NOT NULL DEFAULT '',
	  origin TEXT NOT NULL DEFAULT '',
	  ingredients TEXT NOT NULL DEFAULT '',
	  weight TEXT NOT NULL DEFAULT '',
	  weight_unit TEXT NOT NULL DEFAULT 'g',
	  price TEXT NOT NULL DEFAULT '',
	  shelf_life_days INTEGER NOT NULL DEFAULT 0,
	  created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE TABLE IF NOT EXISTS print_jobs (
	  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	  tenant_id BIGINT NOT NULL,
	  user_id BIGINT,
	  product_id BIGINT,
	  template_id BIGINT,
	  qty INTEGER NOT NULL,
	  batch TEXT NOT NULL DEFAULT '',
	  created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE INDEX IF NOT EXISTS idx_products_tenant ON products(tenant_id)`,
	`CREATE INDEX IF NOT EXISTS idx_templates_tenant ON templates(tenant_id)`,
	`CREATE INDEX IF NOT EXISTS idx_jobs_tenant ON print_jobs(tenant_id, id)`,
}

var errEmailTaken = errors.New("that email is already registered")

type User struct {
	ID         int64
	TenantID   int64
	TenantName string
	Email      string
	Role       string
	hash       string
}
type Template struct {
	ID   int64
	Name string
	ZPL  string
}
type Product struct {
	ID            int64
	Name          string
	TemplateID    int64 // 0 = none
	Barcode       string
	Origin        string
	Ingredients   string
	Weight        string
	WeightUnit    string
	Price         string
	ShelfLifeDays int
}
type Job struct {
	When, Product, Batch, Email string
	Qty                         int
}

// rebind rewrites the ? placeholders used in the queries below to PostgreSQL's $1, $2, ... form.
func rebind(q string) string {
	var b strings.Builder
	n := 0
	for i := 0; i < len(q); i++ {
		if q[i] == '?' {
			n++
			fmt.Fprintf(&b, "$%d", n)
			continue
		}
		b.WriteByte(q[i])
	}
	return b.String()
}

// Thin wrappers so every query goes through rebind.
func (a *App) exec(q string, args ...any) (sql.Result, error) { return a.db.Exec(rebind(q), args...) }
func (a *App) query(q string, args ...any) (*sql.Rows, error) { return a.db.Query(rebind(q), args...) }
func (a *App) queryRow(q string, args ...any) *sql.Row        { return a.db.QueryRow(rebind(q), args...) }

func openDB(dsn string) (*sql.DB, error) {
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(10)
	db.SetMaxIdleConns(5)
	db.SetConnMaxLifetime(time.Hour)
	if err := db.Ping(); err != nil {
		return nil, err
	}
	for _, stmt := range schema {
		if _, err := db.Exec(stmt); err != nil {
			return nil, fmt.Errorf("schema: %w", err)
		}
	}
	return db, nil
}

func nullID(id int64) any {
	if id == 0 {
		return nil
	}
	return id
}

// uniqueErr maps Postgres unique-violation (SQLSTATE 23505) to errEmailTaken.
func uniqueErr(err error) error {
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" {
		return errEmailTaken
	}
	return err
}

